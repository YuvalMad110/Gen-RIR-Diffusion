"""
03_render_replica_images.py
----------------------------
Renders images from Replica 3D scenes using Habitat-Sim for use as visual conditioning
in the Gen-RIR-Diffusion model. Two image types are supported:

  target2source  — Per (receiver, source) pair: camera placed at receiver position,
                   facing exactly toward source. File: tgt{r}_src{s}.png
                   Captures the acoustic path geometry from the listener's perspective.

  room_panorama  — Per scene: 360° equirectangular image from the centroid of all
                   navigable positions. File: {scene_name}_pano_depth.png (or _pano_rgb.png)
                   Captures global room geometry for all pairs in the scene.

Both types support depth and RGB sensor output. Default is depth.
Output folders are named: {view}_{type}/  (e.g. target2source_depth/)

REQUIREMENTS:
  conda activate habitat
  export MAGNUM_LOG=quiet HABITAT_SIM_LOG=quiet

  habitat-sim v0.3.3 must be installed in the active conda environment.
  Run: conda activate habitat

COORDINATE SYSTEM:
  points.txt uses Z-up coordinates (X, Y = horizontal; Z = constant floor height).
  Habitat-Sim uses Y-up. Transform applied: habitat_pos = (x_pts, z_pts, y_pts).
  Heading angles 0/90/180/270 map to facing directions in Habitat's coordinate frame.
  *** Verify visually on a test run before processing all scenes. ***

Usage:
    conda activate habitat
    python3 data/data_preparation/03_render_replica_images.py --scenes office_1 --max-pairs 10
    python3 data/data_preparation/03_render_replica_images.py  # full render, all scenes
"""

